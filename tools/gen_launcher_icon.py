#!/usr/bin/env python3
"""
Generates the "Shutter + Frame" launcher icon as Android vector drawables:
a glossy jade shutter button in a metal ring, framed by viewfinder corners, on a softly lit obsidian tile.

    python3 -I tools/gen_launcher_icon.py

Writes app/src/main/res/drawable/ic_launcher_{background,foreground,monochrome}.xml.
The mark is drawn on a 120-unit grid and scaled so its farthest point (a corner's tip) stays inside the
adaptive icon's 66dp safe circle, so no launcher mask ever clips it.
"""
import math
import os

RES = os.path.join(os.path.dirname(__file__), "..", "app", "src", "main", "res", "drawable")
C = 60.0
INSET, ARM, CORNER_SW, BEND = 24.0, 14.0, 5.0, 4.0
R = 25.0  # shutter well radius

# Farthest point of the mark from the centre: the rounded corner's outer edge.
reach = math.hypot(C - INSET - BEND * (1 - 1 / math.sqrt(2)), C - INSET - BEND * (1 - 1 / math.sqrt(2))) + CORNER_SW / 2
SCALE = 33.0 / reach          # dp per unit: fits the 66dp safe circle
OFFSET = (108 - 120 * SCALE) / 2


def circle(cx, cy, r):
    return f"M{cx - r:.2f},{cy:.2f} a{r:.2f},{r:.2f} 0 1,0 {2 * r:.2f},0 a{r:.2f},{r:.2f} 0 1,0 {-2 * r:.2f},0 Z"


def corner_paths():
    lo, hi, a, b = INSET, 120 - INSET, ARM, BEND
    return [
        f"M{lo},{lo + a} V{lo + b} Q{lo},{lo} {lo + b},{lo} H{lo + a}",
        f"M{hi - a},{lo} H{hi - b} Q{hi},{lo} {hi},{lo + b} V{lo + a}",
        f"M{hi},{hi - a} V{hi - b} Q{hi},{hi} {hi - b},{hi} H{hi - a}",
        f"M{lo + a},{hi} H{lo + b} Q{lo},{hi} {lo},{hi - b} V{hi - a}",
    ]


def radial(cx, cy, r, stops):
    items = "".join(f'<item android:offset="{o}" android:color="{c}"/>' for o, c in stops)
    return (f'<aapt:attr name="android:fillColor"><gradient android:type="radial" android:centerX="{cx:.2f}" '
            f'android:centerY="{cy:.2f}" android:gradientRadius="{r:.2f}">{items}</gradient></aapt:attr>')


METAL = ('<aapt:attr name="android:strokeColor"><gradient android:type="linear" android:startX="20" android:startY="18" '
         'android:endX="100" android:endY="104"><item android:offset="0" android:color="#FFFFFFFF"/>'
         '<item android:offset="0.45" android:color="#FFE4EAE5"/><item android:offset="0.7" android:color="#FFAEB8B1"/>'
         '<item android:offset="1" android:color="#FFEEF2EE"/></gradient></aapt:attr>')

HEAD = ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/gen_launcher_icon.py. Do not edit. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"\n'
        '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n')


def group(body):
    return (f'    <group android:scaleX="{SCALE:.4f}" android:scaleY="{SCALE:.4f}" '
            f'android:translateX="{OFFSET:.3f}" android:translateY="{OFFSET:.3f}">\n{body}    </group>\n')


def foreground():
    dome_r = R * 0.7
    hl_cx, hl_cy = C - R * 0.22, C - R * 0.3
    body = ""
    body += f'        <path android:pathData="{circle(C, C, R * 1.25)}">{radial(C, C, R * 1.25, [(0, "#8C4FC28E"), (1, "#004FC28E")])}</path>\n'
    body += f'        <path android:pathData="{circle(C, C, R)}" android:fillColor="#FF0A0D0B"/>\n'
    body += f'        <path android:pathData="{circle(C, C, R * 0.93)}" android:strokeWidth="{R * 0.14:.2f}">{METAL}</path>\n'
    body += (f'        <path android:pathData="{circle(C, C, dome_r)}">'
             f'{radial(C - dome_r * 0.2, C - dome_r * 0.32, dome_r * 1.4, [(0, "#FF8FE9BE"), (0.55, "#FF4FC28E"), (1, "#FF257552")])}</path>\n')
    body += (f'        <group android:rotation="-30" android:pivotX="{hl_cx:.2f}" android:pivotY="{hl_cy:.2f}">\n'
             f'            <path android:pathData="M{hl_cx - R * 0.28:.2f},{hl_cy:.2f} a{R * 0.28:.2f},{R * 0.14:.2f} 0 1,0 {R * 0.56:.2f},0 '
             f'a{R * 0.28:.2f},{R * 0.14:.2f} 0 1,0 {-R * 0.56:.2f},0 Z" android:fillColor="#47FFFFFF"/>\n        </group>\n')
    for d in corner_paths():
        body += (f'        <path android:pathData="{d}" android:strokeWidth="{CORNER_SW}" android:strokeLineCap="round" '
                 f'android:strokeLineJoin="round">{METAL}</path>\n')
    return HEAD + group(body) + "</vector>\n"


def monochrome():
    # Themed icons tint one colour; keep the shapes, drop the light and gradients.
    body = f'        <path android:pathData="{circle(C, C, R * 0.93)}" android:strokeWidth="{R * 0.14:.2f}" android:strokeColor="#FFFFFFFF"/>\n'
    body += f'        <path android:pathData="{circle(C, C, R * 0.7)}" android:fillColor="#FFFFFFFF"/>\n'
    for d in corner_paths():
        body += (f'        <path android:pathData="{d}" android:strokeWidth="{CORNER_SW}" android:strokeColor="#FFFFFFFF" '
                 f'android:strokeLineCap="round" android:strokeLineJoin="round"/>\n')
    return HEAD + group(body) + "</vector>\n"


def background():
    return (HEAD + f'    <path android:pathData="M0,0 H108 V108 H0 Z">'
            f'{radial(54, 30.2, 86, [(0, "#FF202A24"), (1, "#FF0C100E")])}</path>\n</vector>\n')


for name, text in [("ic_launcher_foreground", foreground()), ("ic_launcher_monochrome", monochrome()), ("ic_launcher_background", background())]:
    with open(os.path.join(RES, name + ".xml"), "w") as fh:
        fh.write(text)
print(f"scale {SCALE:.3f} dp/unit, mark spans {120 * SCALE:.1f}dp of 108dp")
